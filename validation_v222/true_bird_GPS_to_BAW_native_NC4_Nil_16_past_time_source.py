def public_WCS_centre():
    lon,lat=Transformer.from_crs("EPSG:28992","EPSG:4326",always_xy=True).transform(
        *FROZEN_PUBLIC_CENTRE_RD)
    if not (4.1769<lon<7.3397 and 52.8632<lat<53.9412):
        raise ValueError("SOURCE_STOP_PUBLISHED_VLIELAND_HARBOR_OUTSIDE_NATIVE_MODEL")
    return lat,lon

def fixed_model_source_knot(year,month,hour):
    if year not in YEAR_SOURCE_N or month not in FROZEN_MONTHS or hour not in FROZEN_HOURS:
        raise ValueError("SOURCE_STOP_UNFROZEN_YEAR_MONTH_OR_HOUR")
    return datetime(year,month,FROZEN_DAY,hour,0,0,tzinfo=timezone.utc)

def fixed_source_WCS_GetCoverage(year,month,hour):
    t=fixed_model_source_knot(year,month,hour)
    lat,lon=public_WCS_centre()
    url=urllib.parse.urlsplit(CANDIDATE[str(year)])
    q=[
       ("service","WCS"),("version","2.0.1"),("request","GetCoverage"),
       ("coverageId",FROZEN_COVERAGE_IDS[str(year)]),
       ("format",FROZEN_FORMAT),
       ("subset",f"Lat({lat-FROZEN_HALF_DEGREES_LAT:.6f},{lat+FROZEN_HALF_DEGREES_LAT:.6f})"),
       ("subset",f"Long({lon-FROZEN_HALF_DEGREES_LON:.6f},{lon+FROZEN_HALF_DEGREES_LON:.6f})"),
       ("subset",'time("'+t.strftime("%Y-%m-%dT%H:%M:%S.000Z")+'")'),
    ]
    return urllib.parse.urlunsplit((url.scheme,url.netloc,url.path,
                                    urllib.parse.urlencode(q),""))

def source_query_in_fixed_16(url,year,month,hour):
    return (year in YEAR_SOURCE_N and month in FROZEN_MONTHS and
            hour in FROZEN_HOURS and url==fixed_source_WCS_GetCoverage(year,month,hour))

def original_native_WCS_bounded_NC4(year,month,hour):
    url=fixed_source_WCS_GetCoverage(year,month,hour)
    if not source_query_in_fixed_16(url,year,month,hour):
        raise ValueError("SOURCE_STOP_UNFROZEN_BAW_NC4_SOURCE_REQUEST")
    req=urllib.request.Request(url,method="GET",headers={
        "User-Agent":"boids-v222-true-original-oystercatcher-vlieland-GPS-to-WCS-Nil-16-source/1.0",
        "Accept":FROZEN_FORMAT})
    op=urllib.request.build_opener(
        urllib.request.HTTPSHandler(context=ssl.create_default_context()),
        DoNotFollow())
    with op.open(req,timeout=75) as r:
        binary=r.read(MAX_NATIVE_NETCDF4_BYTES+1)
        status=r.status
        returned_url=r.geturl()
        content_type=r.headers.get("Content-Type","")
    if status!=200 or returned_url!=url or not binary or len(binary)>MAX_NATIVE_NETCDF4_BYTES:
        raise ValueError("SOURCE_STOP_OFFICIAL_BAW_NC4_HTTP_OR_UNBOUNDED")
    if not binary.startswith(HDF5_MAGIC) or "netcdf" not in content_type.lower():
        raise ValueError("SOURCE_STOP_YEAR_WCS_DID_NOT_RETURN_TRUE_NETCDF4")
    return binary,{
        "original_source_WCS_NC4_SHA256":hashlib.sha256(binary).hexdigest(),
        "original_source_NC4_bytes":len(binary),
        "source_native_content_type":content_type,
        "native_CA_TLS_and_no_redirect_verified":True,
        "original_NC4_binary_NOT_persisted":True}

def eligible_bird_source_bin(event,year,month,hour):
    timestamp=event.get("source_utc_event")
    if not isinstance(timestamp,datetime) or timestamp.tzinfo is None:
        raise ValueError("SOURCE_STOP_ORIGINAL_BIRD_EVENT_NOT_OFFSET_AWARE")
    instant=timestamp.astimezone(timezone.utc)
    knot=fixed_model_source_knot(year,month,hour)
    # Selection on clock only. No ACC Y, GPS support or tide datum chosen here.
    return knot<=instant<knot+timedelta(minutes=FROZEN_WINDOW_MINUTES)

def freeze_original_bird_source_pilot(year,common,indices):
    if year not in YEAR_SOURCE_N:
        raise ValueError("SOURCE_STOP_UNDECLARED_ORIGINAL_BIRD_SOURCE_YEAR")
    if len(common)!=YEAR_SOURCE_N[year]["original_common"] or len(indices)!=YEAR_SOURCE_N[year]["previous15"]:
        raise ValueError("SOURCE_STOP_ORIGINAL_PREV15_COHORT_MEMBERSHIP_CHANGED")
    groups={(mon,h):[] for mon in FROZEN_MONTHS for h in FROZEN_HOURS}
    for index in indices:
        event,solar,_,_=common[int(index)]
        if solar not in ("day","night") or event.get("source_month") not in FROZEN_MONTHS:
            raise ValueError("SOURCE_STOP_NATIVE_ORIGINAL_BIRD_SOLAR_OR_MONTH")
        stamp=event.get("source_utc_event")
        if not isinstance(stamp,datetime) or stamp.tzinfo is None:
            raise ValueError("SOURCE_STOP_ORIGINAL_BIRD_UTC_TIME_UNVERIFIED")
        ts=stamp.astimezone(timezone.utc)
        if ts.year!=year or ts.month!=event["source_month"]:
            raise ValueError("SOURCE_STOP_ORIGINAL_SOURCE_BIRD_TIMESTAMP_YEAR_MONTH_WRONG")
        if ts.day!=FROZEN_DAY or ts.hour not in FROZEN_HOURS:
            continue
        if not eligible_bird_source_bin(event,year,ts.month,ts.hour):
            continue
        lat=float(event["source_lat"])
        lon=float(event["source_lon"])
        if not (math.isfinite(lat) and math.isfinite(lon) and -90<=lat<=90 and -180<=lon<=180):
            raise ValueError("SOURCE_STOP_ORIGINAL_BIRD_GPS_NOT_FINITE")
        if event.get("private_bird") is None:
            raise ValueError("SOURCE_STOP_ORIGINAL_PRIVATE_TAGGED_BIRD_ID_UNAVAILABLE")
        # Transient RAM only, never serialize this event's exact GPS or bird ID.
        groups[(ts.month,ts.hour)].append((lat,lon,event["private_bird"]))
    return groups

def interpret_native_WCS_NC4_at_bird_GPS(binary,month,hour,year,selected):
    if not binary.startswith(HDF5_MAGIC) or len(binary)>MAX_NATIVE_NETCDF4_BYTES:
        raise ValueError("SOURCE_STOP_NOT_SMALL_NATIVE_WCS_NC4")
    modeltime=fixed_model_source_knot(year,month,hour)
    lat0,lon0=public_WCS_centre()
    bounds=(lat0-FROZEN_HALF_DEGREES_LAT,lat0+FROZEN_HALF_DEGREES_LAT,
            lon0-FROZEN_HALF_DEGREES_LON,lon0+FROZEN_HALF_DEGREES_LON)
    with Dataset("source_v222_NC4_RAM_only.nc",mode="r",memory=binary) as ds:
        if not {"lat","lon","time"}.issubset(set(ds.variables)):
            raise ValueError("SOURCE_STOP_MODEL_NC4_MISSING_NATIVE_LAT_LON_TIME")
        lat=np.asarray(ds.variables["lat"][:],dtype=float)
        lon=np.asarray(ds.variables["lon"][:],dtype=float)
        if lat.ndim!=1 or lon.ndim!=1 or lat.size<2 or lon.size<2:
            raise ValueError("SOURCE_STOP_NATIVE_NC4_NOT_2D_SOURCE_AXES")
        if not np.all(np.isfinite(lat)) or not np.all(np.isfinite(lon)):
            raise ValueError("SOURCE_STOP_NC4_NONFINITE_SPATIAL_COORDS")
        if not ((np.diff(lat)>0).all() or (np.diff(lat)<0).all()):
            raise ValueError("SOURCE_STOP_NC4_LAT_COORD_NOT_MONOTONIC")
        if not ((np.diff(lon)>0).all() or (np.diff(lon)<0).all()):
            raise ValueError("SOURCE_STOP_NC4_LON_COORD_NOT_MONOTONIC")
        names=[key for key in ds.variables if
            "sea_surface_height" in key.lower() or key.lower()=="wasserstand"]
        if len(names)!=1:
            raise ValueError("SOURCE_STOP_NC4_NO_UNIQUE_YEAR_SSH_SOURCE")
        var=ds.variables[names[0]]
        if var.dimensions!=("time","lat","lon") or var.shape[0]!=1 or (
           var.shape[1]!=lat.size or var.shape[2]!=lon.size or
           int(np.prod(var.shape))>MAX_NATIVE_GRID_CELLS):
            raise ValueError("SOURCE_STOP_SOURCE_WCS_NC4_BOUNDED_SPATIAL_TIME_GRID_INCORRECT")
        if str(getattr(var,"units",None))!="m" or "_FillValue" not in var.ncattrs():
            raise ValueError("SOURCE_STOP_NC4_SOURCE_MISSING_UNIT_OR_OFFICIAL_NIL")
        fill=float(var.getncattr("_FillValue"))
        if not np.isclose(fill,BAW_WCS_NATIVE_NIL,rtol=1e-6):
            raise ValueError("SOURCE_STOP_NATIVE_SOURCE_NC4_FILL_VALUE_DRIFT")
        if int(ds.variables["time"].size)!=1:
            raise ValueError("SOURCE_STOP_NC4_SOURCE_TIME_NOT_SINGULAR")
        # Use a model knot fixed BEFORE opening this NetCDF4, not a future value.
        times=ds.variables["time"]
        from netCDF4 import num2date
        if "units" not in times.ncattrs():
            raise ValueError("SOURCE_STOP_NATIVE_TIME_AXIS_HAS_NO_UNITS")
        utc=num2date(times[0],times.units,
               calendar=getattr(times,"calendar","standard"),
               only_use_cftime_datetimes=False,only_use_python_datetimes=True)
        if hasattr(utc,"replace") and utc.tzinfo is None:
            utc=utc.replace(tzinfo=timezone.utc)
        if utc.astimezone(timezone.utc)!=modeltime:
            raise ValueError("SOURCE_STOP_NATIVE_NC4_ACTUAL_TIME_KNOT_NOT_FROZEN")
        var.set_auto_maskandscale(False)
        grid=np.asarray(var[:],dtype=float)[0]
        is_nil=np.isfinite(grid)&np.isclose(grid,fill,rtol=1e-6)
        numeric=np.isfinite(grid)&(abs(grid)<=10)
        if np.any(is_nil&numeric):
            raise ValueError("SOURCE_STOP_MODEL_NIL_AND_NUMERIC_CATEGORIES_OVERLAP")
        source_count={
           "original_native_spatial_cell_total":int(grid.size),
           "original_native_model_Nil_cell_n":int(np.count_nonzero(is_nil)),
           "original_native_model_numeric_cell_n":int(np.count_nonzero(numeric)),
           "original_native_model_other_cell_n":int(grid.size-np.count_nonzero(is_nil)-np.count_nonzero(numeric)),
           "native_NC4_model_time_knot_UTC":modeltime.strftime("%Y-%m-%dT%H:%M:%SZ"),
           "original_full_year_publisher_NetCDF4_not_read":True}
        counts={
           "n_actual_original_GPS_ACC_prev15_events_in_fixed_time_window":len(selected),
           "n_bird_events_outside_fixed_native_ROI":0,
           "n_bird_events_inside_ROI_no_native_grid_nearby":0,
           "n_actual_bird_events_nearest_model_grid_accepted":0,
           "n_GPS_matched_native_model_Nil_events":0,
           "n_GPS_matched_native_model_numeric_events":0,
           "n_GPS_matched_native_model_other_events":0,
           "n_distinct_original_tagged_birds_in_time_window_only":len({z[2] for z in selected}),
           "native_bird_GPS_or_ACC_Y_NOT_persisted":True}
        for b_lat,b_lon,_ in selected:
            in_crop=bounds[0]<=b_lat<=bounds[1] and bounds[2]<=b_lon<=bounds[3]
            if not in_crop:
                counts["n_bird_events_outside_fixed_native_ROI"]+=1
                continue
            iy=int(np.argmin(np.abs(lat-b_lat)))
            ix=int(np.argmin(np.abs(lon-b_lon)))
            if abs(float(lat[iy]-b_lat))>FROZEN_NATIVE_NEAREST_MAX_DELTA_DEG or (
                abs(float(lon[ix]-b_lon))>FROZEN_NATIVE_NEAREST_MAX_DELTA_DEG):
                counts["n_bird_events_inside_ROI_no_native_grid_nearby"]+=1
                continue
            counts["n_actual_bird_events_nearest_model_grid_accepted"]+=1
            if is_nil[iy,ix]:
                counts["n_GPS_matched_native_model_Nil_events"]+=1
            elif numeric[iy,ix]:
                counts["n_GPS_matched_native_model_numeric_events"]+=1
            else:
                counts["n_GPS_matched_native_model_other_events"]+=1
        if (counts["n_bird_events_outside_fixed_native_ROI"]+
            counts["n_bird_events_inside_ROI_no_native_grid_nearby"]+
            counts["n_actual_bird_events_nearest_model_grid_accepted"]!=len(selected)):
            raise ValueError("SOURCE_STOP_GPS_ROI_AND_GRID_CLASSIFICATION_NOT_EXHAUSTIVE")
        if (counts["n_GPS_matched_native_model_Nil_events"]+
            counts["n_GPS_matched_native_model_numeric_events"]+
            counts["n_GPS_matched_native_model_other_events"]!=counts["n_actual_bird_events_nearest_model_grid_accepted"]):
            raise ValueError("SOURCE_STOP_MODEL_NIL_AND_NUMERIC_EVENT_COUNTS_NOT_EXHAUSTIVE")
        counts["source_fraction_model_Nil_among_admitted_GPS_events"] = (
            round(counts["n_GPS_matched_native_model_Nil_events"]/
                  counts["n_actual_bird_events_nearest_model_grid_accepted"],8)
            if counts["n_actual_bird_events_nearest_model_grid_accepted"] else None)
        counts["native_source_WCS_cell_is_not_true_coastal_dry_exposure"]=True
        return {"native_model_crop_counts":source_count,
                "true_source_GPS_ACC_event_model_cell_status":counts}

